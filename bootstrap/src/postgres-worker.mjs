/**
 * Small single-concurrency worker for createPostgresEventQueue().
 * It intentionally delegates policy, provider calls and evidence verification to `execute`.
 */
function requiredString(value, name) {
  if (typeof value !== 'string' || !value.trim() || /[\u0000-\u001f]/.test(value)) {
    throw new TypeError(`${name} is required and must not contain control characters`);
  }
  return value;
}

function duration(value, name, min, max) {
  if (!Number.isInteger(value) || value < min || value > max) {
    throw new TypeError(`${name} must be an integer between ${min} and ${max}`);
  }
  return value;
}

function delay(ms, signal) {
  if (signal?.aborted) return Promise.resolve();
  return new Promise(resolve => {
    let settled = false;
    const finish = () => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      signal?.removeEventListener('abort', finish);
      resolve();
    };
    const timer = setTimeout(finish, ms);
    signal?.addEventListener('abort', finish, { once: true });
  });
}

function asError(value) {
  return value instanceof Error ? value : new Error(String(value ?? 'unknown_error'));
}

/**
 * Create a cooperative, one-event-at-a-time PostgreSQL worker.
 *
 * `execute(event, { signal, workerId, leaseToken })` must run the policy-checked workflow and
 * return `{ resultEvidence: { verified: true, evidenceRef, method? }, value? }`. It must honour
 * the AbortSignal where possible and reconcile uncertain external writes before replay.
 * `resultEvidence` is not generated by this module: it must be based on independent verification.
 */
export function createPostgresWorker({
  queue,
  workerId,
  execute,
  leaseMs = 30_000,
  heartbeatMs = Math.floor(leaseMs / 3),
  pollIntervalMs = 1_000,
  maxAttempts = 5,
  baseDelayMs = 1_000,
  maxDelayMs = 3_600_000,
  isRetryableError = () => true,
  onError = () => {}
} = {}) {
  workerId = requiredString(workerId, 'workerId');
  if (!queue || typeof queue.claimNext !== 'function' || typeof queue.extendLease !== 'function' ||
      typeof queue.complete !== 'function' || typeof queue.fail !== 'function') {
    throw new TypeError('queue must implement claimNext, extendLease, complete and fail');
  }
  if (typeof execute !== 'function') throw new TypeError('execute must be a function');
  if (typeof isRetryableError !== 'function') throw new TypeError('isRetryableError must be a function');
  if (typeof onError !== 'function') throw new TypeError('onError must be a function');
  duration(leaseMs, 'leaseMs', 100, 3_600_000);
  duration(heartbeatMs, 'heartbeatMs', 1, leaseMs - 1);
  duration(pollIntervalMs, 'pollIntervalMs', 1, 3_600_000);
  duration(maxAttempts, 'maxAttempts', 1, 100);
  if (!Number.isFinite(baseDelayMs) || baseDelayMs < 0 || !Number.isFinite(maxDelayMs) || maxDelayMs < baseDelayMs) {
    throw new TypeError('invalid retry delay bounds');
  }

  const stopController = new AbortController();
  let stopRequested = false;
  let startCalled = false;
  let runPromise;
  let activeEventKey = null;

  async function report(error, stage, eventKey = activeEventKey) {
    try { await onError({ error: asError(error), stage, eventKey, workerId }); } catch { /* logging must not crash the worker */ }
  }

  async function runOnce() {
    let event;
    try {
      event = await queue.claimNext({ workerId, leaseMs });
    } catch (error) {
      await report(error, 'claim');
      return { status: 'claim_error', error: asError(error) };
    }
    if (!event) return { status: 'idle' };
    if (!event.lease?.token || event.lease.workerId !== workerId || typeof event.eventKey !== 'string') {
      const error = new Error('queue_returned_invalid_lease');
      await report(error, 'claim_validation', event.eventKey);
      return { status: 'invalid_claim', error };
    }

    const { eventKey } = event;
    const leaseToken = event.lease.token;
    activeEventKey = eventKey;
    const executeController = new AbortController();
    const heartbeatController = new AbortController();
    let leaseLostError = null;
    let rejectLeaseLost;
    const leaseLostPromise = new Promise((_, reject) => { rejectLeaseLost = reject; });
    // The rejection is also consumed by Promise.race below; attach a defensive handler for early failures.
    leaseLostPromise.catch(() => {});

    const heartbeatTask = (async () => {
      while (!heartbeatController.signal.aborted) {
        await delay(heartbeatMs, heartbeatController.signal);
        if (heartbeatController.signal.aborted) break;
        try {
          await queue.extendLease({ eventKey, workerId, leaseToken, leaseMs });
        } catch (error) {
          if (!heartbeatController.signal.aborted) {
            leaseLostError = asError(error);
            executeController.abort(leaseLostError);
            rejectLeaseLost(leaseLostError);
          }
          break;
        }
      }
    })();

    let executionResult;
    let executionError = null;
    try {
      executionResult = await Promise.race([
        Promise.resolve().then(() => execute(event, {
          signal: executeController.signal,
          workerId,
          leaseToken
        })),
        leaseLostPromise
      ]);
    } catch (error) {
      executionError = asError(error);
    } finally {
      heartbeatController.abort();
      await heartbeatTask;
      activeEventKey = null;
    }

    // Once heartbeat/fencing is uncertain, do not attempt completion or failure settlement.
    // Any external call already in flight must be reconciled before an operator/policy permits replay.
    if (leaseLostError) {
      await report(leaseLostError, 'lease_lost', eventKey);
      return { status: 'lease_lost', eventKey, error: leaseLostError };
    }

    if (executionError) {
      let retryable = true;
      try { retryable = Boolean(isRetryableError(executionError)); }
      catch (policyError) {
        await report(policyError, 'retry_policy', eventKey);
        retryable = false;
      }
      try {
        const failed = await queue.fail({
          eventKey, workerId, leaseToken, error: executionError, retryable,
          maxAttempts, baseDelayMs, maxDelayMs
        });
        return { status: failed.status, eventKey, error: executionError, event: failed };
      } catch (settlementError) {
        // Settlement may have committed before a connection failure; never blindly settle a second time.
        await report(settlementError, 'failure_settlement', eventKey);
        return { status: 'settlement_error', eventKey, error: asError(settlementError), originalError: executionError };
      }
    }

    const resultEvidence = executionResult?.resultEvidence;
    if (!resultEvidence || resultEvidence.verified !== true ||
        typeof resultEvidence.evidenceRef !== 'string' || !resultEvidence.evidenceRef.trim()) {
      const error = new TypeError('execute must return independently verified resultEvidence.evidenceRef');
      try {
        const failed = await queue.fail({
          eventKey, workerId, leaseToken, error, retryable: false,
          maxAttempts, baseDelayMs, maxDelayMs
        });
        return { status: failed.status, eventKey, error, event: failed };
      } catch (settlementError) {
        await report(settlementError, 'evidence_settlement', eventKey);
        return { status: 'settlement_error', eventKey, error: asError(settlementError), originalError: error };
      }
    }

    try {
      const completed = await queue.complete({ eventKey, workerId, leaseToken, resultEvidence });
      return { status: 'succeeded', eventKey, event: completed, value: executionResult.value };
    } catch (error) {
      // Completion can be ambiguous on connection loss. Do not follow a failed completion call with `fail`.
      await report(error, 'completion_settlement', eventKey);
      return { status: 'settlement_error', eventKey, error: asError(error) };
    }
  }

  async function loop() {
    while (!stopRequested) {
      await runOnce();
      if (!stopRequested) await delay(pollIntervalMs, stopController.signal);
    }
  }

  return Object.freeze({
    runOnce,
    start() {
      if (startCalled) return runPromise;
      if (stopRequested) throw new Error('worker_already_stopped');
      startCalled = true;
      runPromise = loop().catch(async error => {
        await report(error, 'worker_loop');
        throw error;
      });
      return runPromise;
    },
    async stop() {
      stopRequested = true;
      stopController.abort();
      if (runPromise) await runPromise;
    },
    get isRunning() { return startCalled && !stopRequested; },
    get activeEventKey() { return activeEventKey; }
  });
}